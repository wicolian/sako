'use client'

import { useState, useEffect, use } from 'react'
import Link from 'next/link'
import {
  ShieldCheck,
  Download,
  Copy,
  CheckCircle2,
  ExternalLink,
  FileText,
  Link2,
  Calendar,
  Building,
} from 'lucide-react'
import { Button } from '@/components/ui/button'
import { Badge } from '@/components/ui/badge'
import { Card, CardContent, CardHeader, CardTitle, CardDescription } from '@/components/ui/card'

interface SharedPack {
  pack: {
    id: string
    name: string
    description: string | null
    exportFormat: string
    createdAt: string
    expiresAt: string | null
  }
  claims: Array<{
    id: string
    text: string
    claim_type: string
    category: string
    claim_evidence_links: Array<{
      evidence: {
        id: string
        title: string
        type: string
        tier: string
        url: string | null
      }
    }>
  }>
  workspace: {
    name: string
  }
}

export default function SharePage({ params }: { params: Promise<{ token: string }> }) {
  const { token } = use(params)
  const [data, setData] = useState<SharedPack | null>(null)
  const [loading, setLoading] = useState(true)
  const [error, setError] = useState<string | null>(null)
  const [copied, setCopied] = useState(false)

  useEffect(() => {
    fetchSharedPack()
  }, [token])

  async function fetchSharedPack() {
    setLoading(true)
    try {
      const res = await fetch(`/api/share/${token}`)
      if (!res.ok) {
        const errData = await res.json()
        setError(errData.error || 'Failed to load shared pack')
        return
      }
      const packData = await res.json()
      setData(packData)
    } catch (err) {
      setError('Failed to load shared pack')
    } finally {
      setLoading(false)
    }
  }

  async function copyAllClaims() {
    if (!data) return
    const text = data.claims.map(c => c.text).join('\n\n')
    await navigator.clipboard.writeText(text)
    setCopied(true)
    setTimeout(() => setCopied(false), 2000)
  }

  function downloadAsJSON() {
    if (!data) return
    const exportData = {
      pack: data.pack,
      claims: data.claims.map(c => ({
        text: c.text,
        type: c.claim_type,
        category: c.category,
        evidence: c.claim_evidence_links.map(l => ({
          title: l.evidence.title,
          tier: l.evidence.tier,
          url: l.evidence.url,
        })),
      })),
      exportedAt: new Date().toISOString(),
      source: 'Sako Composer',
    }
    const blob = new Blob([JSON.stringify(exportData, null, 2)], { type: 'application/json' })
    const url = URL.createObjectURL(blob)
    const a = document.createElement('a')
    a.href = url
    a.download = `${data.pack.name.replace(/\s+/g, '-').toLowerCase()}-claims.json`
    a.click()
    URL.revokeObjectURL(url)
  }

  function downloadAsMarkdown() {
    if (!data) return
    let md = `# ${data.pack.name}\n\n`
    md += `**Source:** ${data.workspace.name}\n`
    md += `**Exported:** ${new Date().toLocaleDateString()}\n\n`
    
    if (data.pack.description) {
      md += `${data.pack.description}\n\n`
    }
    
    md += `---\n\n## Claims\n\n`
    
    data.claims.forEach((claim, i) => {
      md += `### ${i + 1}. ${claim.text}\n\n`
      md += `- **Type:** ${claim.claim_type}\n`
      md += `- **Category:** ${claim.category}\n`
      
      if (claim.claim_evidence_links.length > 0) {
        md += `- **Evidence:**\n`
        claim.claim_evidence_links.forEach(link => {
          md += `  - ${link.evidence.title} (Tier ${link.evidence.tier})`
          if (link.evidence.url) {
            md += ` - [Link](${link.evidence.url})`
          }
          md += '\n'
        })
      }
      md += '\n'
    })
    
    md += `---\n\n*Generated by Sako Composer*`
    
    const blob = new Blob([md], { type: 'text/markdown' })
    const url = URL.createObjectURL(blob)
    const a = document.createElement('a')
    a.href = url
    a.download = `${data.pack.name.replace(/\s+/g, '-').toLowerCase()}-claims.md`
    a.click()
    URL.revokeObjectURL(url)
  }

  if (loading) {
    return (
      <div className="min-h-screen flex items-center justify-center bg-background text-foreground">
        <div className="animate-pulse text-muted-foreground">Loading...</div>
      </div>
    )
  }

  if (error) {
    return (
      <div className="min-h-screen flex items-center justify-center p-4">
        <Card className="max-w-md w-full">
          <CardContent className="py-12 text-center">
            <div className="w-16 h-16 bg-destructive/10 rounded-full flex items-center justify-center mx-auto mb-4">
              <ShieldCheck className="w-8 h-8 text-red-500" />
            </div>
            <h2 className="text-xl font-semibold mb-2">Link Not Available</h2>
            <p className="text-muted-foreground mb-6">{error}</p>
            <Button asChild>
              <Link href="/">Go to Sako Composer</Link>
            </Button>
          </CardContent>
        </Card>
      </div>
    )
  }

  if (!data) return null

  return (
    <div className="min-h-screen bg-gradient-to-b from-background to-muted/30">
      {/* Header */}
      <div className="border-b bg-background/80 backdrop-blur-sm sticky top-0 z-10">
        <div className="max-w-4xl mx-auto px-4 py-4 flex items-center justify-between">
          <div className="flex items-center gap-3">
            <div className="w-10 h-10 rounded-lg bg-primary flex items-center justify-center">
              <ShieldCheck className="w-5 h-5 text-primary-foreground" />
            </div>
            <div>
              <p className="font-semibold">Sako Composer</p>
              <p className="text-xs text-muted-foreground">Claim Pack</p>
            </div>
          </div>
          <Button asChild variant="outline">
            <Link href="/">
              Open in Sako
              <ExternalLink className="w-4 h-4 ml-2" />
            </Link>
          </Button>
        </div>
      </div>

      {/* Content */}
      <div className="max-w-4xl mx-auto px-4 py-8 space-y-6">
        {/* Pack Header */}
        <div className="text-center mb-8">
          <h1 className="text-3xl font-bold mb-2">{data.pack.name}</h1>
          {data.pack.description && (
            <p className="text-muted-foreground mb-4">{data.pack.description}</p>
          )}
          <div className="flex items-center justify-center gap-4 text-sm text-muted-foreground">
            <span className="flex items-center gap-1">
              <Building className="w-4 h-4" />
              {data.workspace.name}
            </span>
            <span className="flex items-center gap-1">
              <Calendar className="w-4 h-4" />
              {new Date(data.pack.createdAt).toLocaleDateString()}
            </span>
            <span className="flex items-center gap-1">
              <FileText className="w-4 h-4" />
              {data.claims.length} claims
            </span>
          </div>
        </div>

        {/* Actions */}
        <Card>
          <CardContent className="py-4">
            <div className="flex flex-wrap items-center justify-center gap-3">
              <Button onClick={copyAllClaims} variant="outline">
                {copied ? (
                  <>
                    <CheckCircle2 className="w-4 h-4 mr-2 text-green-500" />
                    Copied!
                  </>
                ) : (
                  <>
                    <Copy className="w-4 h-4 mr-2" />
                    Copy All Claims
                  </>
                )}
              </Button>
              <Button onClick={downloadAsJSON} variant="outline">
                <Download className="w-4 h-4 mr-2" />
                Download JSON
              </Button>
              <Button onClick={downloadAsMarkdown} variant="outline">
                <Download className="w-4 h-4 mr-2" />
                Download Markdown
              </Button>
            </div>
          </CardContent>
        </Card>

        {/* Claims */}
        <div className="space-y-4">
          {data.claims.map((claim, i) => (
            <Card key={claim.id}>
              <CardHeader className="pb-3">
                <div className="flex items-start gap-4">
                  <div className="w-8 h-8 rounded-full bg-primary/10 flex items-center justify-center text-sm font-medium text-primary shrink-0">
                    {i + 1}
                  </div>
                  <div className="flex-1 min-w-0">
                    <CardTitle className="text-base font-medium leading-relaxed">
                      {claim.text}
                    </CardTitle>
                    <div className="flex items-center gap-2 mt-2">
                      <Badge variant="outline" className="text-xs capitalize">
                        {claim.claim_type}
                      </Badge>
                      <Badge variant="outline" className="text-xs capitalize">
                        {claim.category}
                      </Badge>
                    </div>
                  </div>
                </div>
              </CardHeader>
              {claim.claim_evidence_links.length > 0 && (
                <CardContent className="pt-0">
                  <div className="ml-12 pl-4 border-l-2 border-muted">
                    <p className="text-xs text-muted-foreground mb-2 flex items-center gap-1">
                      <Link2 className="w-3 h-3" />
                      Supporting Evidence
                    </p>
                    <div className="space-y-2">
                      {claim.claim_evidence_links.map((link) => (
                        <div
                          key={link.evidence.id}
                          className="flex items-center justify-between text-sm"
                        >
                          <span>{link.evidence.title}</span>
                          <div className="flex items-center gap-2">
                            <Badge variant="secondary" className="text-xs">
                              Tier {link.evidence.tier}
                            </Badge>
                            {link.evidence.url && (
                              <a
                                href={link.evidence.url}
                                target="_blank"
                                rel="noopener noreferrer"
                                className="text-primary hover:underline"
                              >
                                <ExternalLink className="w-3 h-3" />
                              </a>
                            )}
                          </div>
                        </div>
                      ))}
                    </div>
                  </div>
                </CardContent>
              )}
            </Card>
          ))}
        </div>

        {/* Footer */}
        <div className="text-center pt-8 pb-16">
          <p className="text-sm text-muted-foreground mb-4">
            Want to create governed marketing claims for your team?
          </p>
          <Button asChild>
            <Link href="/">Try Sako Composer</Link>
          </Button>
        </div>
      </div>
    </div>
  )
}
