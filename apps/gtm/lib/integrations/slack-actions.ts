/**
 * Slack Actions
 * 
 * AI-powered actions that can be triggered from Slack.
 */

import { generateText } from '@/lib/ai/langsmith-ai'
import { MODELS } from '@/lib/ai/ai-sdk-client'
import { createServiceClient } from '@/lib/supabase/service'
import { getSlackConnection, sendSlackMessage, buildNotificationBlocks } from './slack'
import { validateClaim } from '@/lib/claims/validator'
import { getCampaignHealthScore } from '@/lib/monitoring/campaign-health'

export interface SlackCommandContext {
  workspaceId: string
  userId: string
  channelId: string
  responseUrl: string
}

/**
 * Handle /sako generate [brief] command
 */
export async function handleGenerateCommand(
  ctx: SlackCommandContext,
  brief: string
): Promise<void> {
  const connection = await getSlackConnection(ctx.workspaceId)
  if (!connection) {
    throw new Error('Slack not connected')
  }

  // Generate content
  const { text: content } = await generateText({
    model: MODELS.FAST,
    system: `You are a marketing copywriter. Generate concise, engaging marketing content based on the brief. Keep responses under 500 characters for Slack.`,
    prompt: brief,
    maxOutputTokens: 200,
  })

  // Send response
  await sendSlackMessage(connection.access_token, {
    channel: ctx.channelId,
    text: `Generated content for: "${brief}"`,
    blocks: [
      {
        type: 'section',
        text: {
          type: 'mrkdwn',
          text: `*Generated Content:*\n\n${content}`,
        },
      },
      {
        type: 'context',
        elements: [
          {
            type: 'mrkdwn',
            text: `🤖 Generated by Sako | _Based on: "${brief.slice(0, 50)}${brief.length > 50 ? '...' : ''}"_`,
          },
        ],
      },
      {
        type: 'actions',
        elements: [
          {
            type: 'button',
            text: {
              type: 'plain_text',
              text: '✏️ Edit in Sako',
              emoji: true,
            },
            url: `${process.env.NEXT_PUBLIC_APP_URL}/campaigns/new?brief=${encodeURIComponent(brief)}`,
          },
          {
            type: 'button',
            text: {
              type: 'plain_text',
              text: '🔄 Regenerate',
              emoji: true,
            },
            action_id: 'regenerate_content',
            value: brief,
          },
        ],
      },
    ],
  })
}

/**
 * Handle /sako validate [claim] command
 */
export async function handleValidateCommand(
  ctx: SlackCommandContext,
  claim: string
): Promise<void> {
  const connection = await getSlackConnection(ctx.workspaceId)
  if (!connection) {
    throw new Error('Slack not connected')
  }

  // Validate the claim
  const result = await validateClaim(claim, ctx.workspaceId)

  const statusEmoji: Record<string, string> = {
    valid: '✅',
    needs_evidence: '⚠️',
    flagged: '❌',
    pending: '⏳',
  }

  const statusColor: Record<string, string> = {
    valid: 'good',
    needs_evidence: 'warning',
    flagged: 'danger',
    pending: '#888888',
  }

  await sendSlackMessage(connection.access_token, {
    channel: ctx.channelId,
    text: `Claim validation: ${result.status}`,
    blocks: [
      {
        type: 'header',
        text: {
          type: 'plain_text',
          text: `${statusEmoji[result.status]} Claim Validation`,
          emoji: true,
        },
      },
      {
        type: 'section',
        text: {
          type: 'mrkdwn',
          text: `*Claim:*\n"${claim}"`,
        },
      },
      {
        type: 'section',
        text: {
          type: 'mrkdwn',
          text: `*Status:* ${result.status.replace('_', ' ').toUpperCase()}\n*Confidence:* ${Math.round(result.confidence * 100)}%`,
        },
      },
    ],
    attachments: result.issues && result.issues.length > 0 ? [
      {
        color: statusColor[result.status],
        title: 'Issues Found',
        text: result.issues.map((i: string) => `• ${i}`).join('\n'),
      },
    ] : undefined,
  })
}

/**
 * Handle /sako status [campaign] command
 */
export async function handleStatusCommand(
  ctx: SlackCommandContext,
  campaignName: string
): Promise<void> {
  const supabase = createServiceClient()
  const connection = await getSlackConnection(ctx.workspaceId)
  if (!connection) {
    throw new Error('Slack not connected')
  }

  // Find campaign
  const { data: campaign } = await supabase
    .from('campaigns')
    .select('id, name, status, health_score')
    .eq('workspace_id', ctx.workspaceId)
    .ilike('name', `%${campaignName}%`)
    .limit(1)
    .single()

  if (!campaign) {
    await sendSlackMessage(connection.access_token, {
      channel: ctx.channelId,
      text: `❌ Campaign "${campaignName}" not found`,
    })
    return
  }

  // Get health score
  const health = await getCampaignHealthScore(campaign.id)

  const healthEmoji = health.overall >= 80 ? '🟢' : health.overall >= 50 ? '🟡' : '🔴'

  await sendSlackMessage(connection.access_token, {
    channel: ctx.channelId,
    text: `Campaign status: ${campaign.name}`,
    blocks: [
      {
        type: 'header',
        text: {
          type: 'plain_text',
          text: `📊 Campaign Status: ${campaign.name}`,
          emoji: true,
        },
      },
      {
        type: 'section',
        text: {
          type: 'mrkdwn',
          text: [
            `*Status:* ${campaign.status}`,
            `*Health Score:* ${healthEmoji} ${health.overall}/100`,
            '',
            '*Breakdown:*',
            `• Compliance: ${health.factors.compliance}/100`,
            `• Freshness: ${health.factors.freshness}/100`,
            `• Performance: ${health.factors.performance}/100`,
          ].join('\n'),
        },
      },
      {
        type: 'actions',
        elements: [
          {
            type: 'button',
            text: {
              type: 'plain_text',
              text: '📈 View in Sako',
              emoji: true,
            },
            url: `${process.env.NEXT_PUBLIC_APP_URL}/campaigns/${campaign.id}`,
          },
        ],
      },
    ],
  })
}

/**
 * Send campaign notification to Slack
 */
export async function sendCampaignNotification(
  workspaceId: string,
  notification: {
    type: 'published' | 'flagged' | 'approval_needed' | 'health_alert'
    campaignId: string
    campaignName: string
    message: string
    urgency?: 'low' | 'medium' | 'high'
  }
): Promise<boolean> {
  const connection = await getSlackConnection(workspaceId)
  if (!connection) return false

  const webhook = (connection.metadata as { webhook?: { url: string } })?.webhook?.url
  if (!webhook) return false

  const typeConfig: Record<string, { title: string; type: 'info' | 'success' | 'warning' | 'error' }> = {
    published: { title: 'Campaign Published', type: 'success' },
    flagged: { title: 'Campaign Flagged', type: 'error' },
    approval_needed: { title: 'Approval Needed', type: 'warning' },
    health_alert: { title: 'Health Alert', type: 'warning' },
  }

  const config = typeConfig[notification.type]

  const blocks = buildNotificationBlocks({
    title: `${config.title}: ${notification.campaignName}`,
    description: notification.message,
    type: config.type,
    actions: [
      {
        label: 'View Campaign',
        url: `${process.env.NEXT_PUBLIC_APP_URL}/campaigns/${notification.campaignId}`,
      },
    ],
  })

  const response = await fetch(webhook, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ blocks }),
  })

  return response.ok
}
