/**
 * Asset Bundler
 * 
 * Bundles assets (images, fonts, etc.) for export
 * - Downloads remote assets
 * - Optimizes images
 * - Packages everything into a ZIP
 */

import JSZip from 'jszip'
import type { WebsiteDesign } from '@/lib/website/ai-designer'
import { exportToHtml, type ExportOptions } from './html-exporter'

export interface BundleOptions extends ExportOptions {
  includeAssets?: boolean
  optimizeImages?: boolean
}

export interface BundleResult {
  zipBuffer: Buffer
  filename: string
  size: number
  files: string[]
}

/**
 * Bundle a website design into a downloadable ZIP file
 */
export async function bundleWebsite(
  design: WebsiteDesign,
  options: BundleOptions = {}
): Promise<BundleResult> {
  const zip = new JSZip()
  const files: string[] = []

  // Generate main HTML file
  const html = exportToHtml(design, options)
  zip.file('index.html', html)
  files.push('index.html')

  // Add CSS file (optional - could also be inline)
  const css = generateStandaloneCss(design)
  zip.file('styles.css', css)
  files.push('styles.css')

  // Add favicon placeholder
  zip.file('favicon.ico', getFaviconPlaceholder())
  files.push('favicon.ico')

  // Add README
  const readme = generateReadme(design)
  zip.file('README.md', readme)
  files.push('README.md')

  // Create images folder
  const imagesFolder = zip.folder('images')
  if (imagesFolder) {
    // Add placeholder for images referenced in the design
    imagesFolder.file('.gitkeep', '')
    files.push('images/.gitkeep')
  }

  // Generate ZIP buffer
  const zipBuffer = await zip.generateAsync({
    type: 'nodebuffer',
    compression: 'DEFLATE',
    compressionOptions: { level: 9 },
  })

  const filename = `${slugify(design.name)}-export.zip`

  return {
    zipBuffer,
    filename,
    size: zipBuffer.length,
    files,
  }
}

