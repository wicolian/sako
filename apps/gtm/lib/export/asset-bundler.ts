/**
 * Export an AssetDocument to a specific format
 */
export async function exportAssetDocument(
  assetDoc: { html: string; title?: string; type: string; dimensions?: { width: number; height: number } },
  format: 'png' | 'jpg' | 'pdf' | 'html' | 'zip'
): Promise<{ buffer: Buffer; filename: string; contentType: string }> {
  const title = assetDoc.title ?? 'asset'
  const safeTitle = slugify(title)

  if (format === 'html') {
    const buffer = Buffer.from(assetDoc.html, 'utf-8')
    return { buffer, filename: `${safeTitle}.html`, contentType: 'text/html' }
  }

  if (format === 'pdf') {
    const { renderHtmlToPdf } = await import('@/lib/render/pdf-renderer')
    const result = await renderHtmlToPdf(assetDoc.html, {
      format: 'custom',
      width: assetDoc.dimensions?.width ?? 1200,
      height: assetDoc.dimensions?.height ?? 627,
      printBackground: true,
    })
    return { buffer: result.buffer, filename: `${safeTitle}.pdf`, contentType: 'application/pdf' }
  }

  if (format === 'png' || format === 'jpg') {
    const { renderHtmlToImage } = await import('@/lib/render/html-renderer')
    const result = await renderHtmlToImage(assetDoc.html, {
      width: assetDoc.dimensions?.width ?? 1200,
      height: assetDoc.dimensions?.height ?? 627,
      format,
    })
    const contentType = format === 'jpg' ? 'image/jpeg' : 'image/png'
    return { buffer: result.buffer, filename: `${safeTitle}.${format}`, contentType }
  }

  // ZIP bundle
  const zip = new JSZip()
  zip.file('index.html', assetDoc.html)
  const zipBuffer = await zip.generateAsync({ type: 'nodebuffer', compression: 'DEFLATE' })
  return { buffer: zipBuffer, filename: `${safeTitle}-export.zip`, contentType: 'application/zip' }
}

/**
 * Bundle a full campaign's assets into a ZIP
 */
export async function bundleCampaignAssets(
  assets: Array<{ html: string; title?: string; type: string; dimensions?: { width: number; height: number } }>,
  campaignName: string,
  format: 'html' | 'png' | 'jpg' = 'html'
): Promise<BundleResult> {
  const zip = new JSZip()
  const files: string[] = []

  for (const asset of assets) {
    const safeTitle = slugify(asset.title ?? asset.type)
    const folder = zip.folder(asset.type)
    if (!folder) continue

    if (format === 'html') {
      folder.file(`${safeTitle}.html`, asset.html)
      files.push(`${asset.type}/${safeTitle}.html`)
    } else {
      const exported = await exportAssetDocument(asset, format)
      folder.file(exported.filename, exported.buffer)
      files.push(`${asset.type}/${exported.filename}`)
    }
  }

  const zipBuffer = await zip.generateAsync({
    type: 'nodebuffer',
    compression: 'DEFLATE',
    compressionOptions: { level: 9 },
  })

  return {
    zipBuffer,
    filename: `${slugify(campaignName)}-campaign.zip`,
    size: zipBuffer.length,
    files,
  }
}

/**
 * Extract all image URLs from HTML
 */
export function extractImageUrls(html: string): string[] {
  const urls: string[] = []
  
  // Match img src
  const imgMatches = html.matchAll(/<img[^>]+src="([^"]+)"/g)
  for (const match of imgMatches) {
    if (match[1] && match[1].startsWith('http')) {
      urls.push(match[1])
    }
  }
  
  // Match background-image url()
  const bgMatches = html.matchAll(/background-image:\s*url\(['"]?([^'"]+)['"]?\)/g)
  for (const match of bgMatches) {
    if (match[1] && match[1].startsWith('http')) {
      urls.push(match[1])
    }
  }
  
  return [...new Set(urls)]
}
