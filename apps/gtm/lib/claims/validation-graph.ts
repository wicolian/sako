/**
 * ClaimsOS LangGraph Validation Pipeline (Jan 2026)
 * 
 * A bounded, auditable workflow for claim validation with:
 * - Claim extraction from campaign context
 * - Deterministic rule validation (rules engine has final say)
 * - AI-powered rewrite suggestions (max 2 retries)
 * - Audit trail for all transitions
 * 
 * Uses LangGraph for state machine + AI SDK Gateway for generation.
 */

import { StateGraph, END, START, Annotation } from '@langchain/langgraph';
import { generateStructuredOutput, generateCompliantRewrites } from '@/lib/ai/ai-sdk-client';
import { validateClaim, createDefaultPolicyContext } from './rules-engine';
import { z } from 'zod';
import type {
  ClaimGraphState,
  ClaimCandidate,
  ClaimValidationResult,
  PolicyConfig,
  AuditEvent,
  ClaimType,
  ClaimCategory,
  ClaimStatus,
  ReasonCode,
  EvidenceTier,
} from './types';

// ============================================================================
// Schemas for AI Generation
// ============================================================================

const ClaimsExtractionSchema = z.object({
  claims: z.array(z.object({
    text: z.string().describe('The extracted or generated claim'),
    claimType: z.enum(['hard', 'soft', 'unverified']).describe('hard = factual/measurable, soft = benefit/positioning, unverified = unsupported assertion'),
    category: z.enum(['performance', 'security', 'pricing', 'compliance', 'generic']).describe('Which category this claim belongs to'),
    confidence: z.number().min(0).max(1).describe('AI confidence that this claim is accurate and supportable'),
    sourceEvidence: z.string().optional().describe('Which evidence item supports this claim, if any'),
  })).describe('List of claims extracted from the campaign context'),
});

// Note: Rewrites are generated by generateCompliantRewrites in ai-sdk-client.ts
// which returns { rewrites: [{ original, rewritten, reasoning, riskReduction, preservedIntent }] }
// This schema is kept for reference but the actual schema is in ai-sdk-client.ts

// ============================================================================
// Graph State Definition
// ============================================================================

const GraphState = Annotation.Root({
  // Input
  policy: Annotation<PolicyConfig>({
    reducer: (_, next) => next,
    default: () => createDefaultPolicyContext().policy,
  }),
  evidenceSummaries: Annotation<string[]>({
    reducer: (_, next) => next,
    default: () => [],
  }),
  campaignContext: Annotation<{
    audience?: string;
    goal?: string;
    offer?: string;
    industry?: string;
    brief?: string;
  }>({
    reducer: (_, next) => next,
    default: () => ({}),
  }),
  
  // Processing
  claimCandidates: Annotation<ClaimCandidate[]>({
    reducer: (_, next) => next,
    default: () => [],
  }),
  validationResults: Annotation<Array<ClaimValidationResult & { claimIndex: number }>>({
    reducer: (_, next) => next,
    default: () => [],
  }),
  retryCount: Annotation<number>({
    reducer: (_, next) => next,
    default: () => 0,
  }),
  
  // Output
  finalClaims: Annotation<Array<{
    text: string;
    type: ClaimType;
    category: ClaimCategory;
    status: ClaimStatus;
    reasonCodes: ReasonCode[];
    riskScore: number;
    requiredEvidenceTier: EvidenceTier | null;
    suggestedRewrites: string[];
  }>>({
    reducer: (_, next) => next,
    default: () => [],
  }),
  
  // Audit
  auditEvents: Annotation<AuditEvent[]>({
    reducer: (prev, next) => [...prev, ...next],
    default: () => [],
  }),
});

type GraphStateType = typeof GraphState.State;

// ============================================================================
// Graph Nodes
// ============================================================================

/**
 * Node 1: Normalize Inputs
 * Parse and validate incoming campaign context and evidence
 */
async function normalizeInputs(state: GraphStateType): Promise<Partial<GraphStateType>> {
  const auditEvent: AuditEvent = {
    entityType: 'claim',
    entityId: 'pipeline',
    action: 'create',
    after: {
      step: 'normalize_inputs',
      campaignContext: state.campaignContext,
      evidenceCount: state.evidenceSummaries.length,
    },
    timestamp: new Date(),
  };

  return {
    auditEvents: [auditEvent],
  };
}

/**
 * Node 2: Propose Claims
 * Use AI SDK Gateway to extract claim candidates from campaign context
 */
async function proposeClaims(state: GraphStateType): Promise<Partial<GraphStateType>> {
  const evidenceContext = state.evidenceSummaries.length > 0
    ? `\n\nAVAILABLE EVIDENCE:\n${state.evidenceSummaries.map((e, i) => `- Evidence ${i + 1}: ${e}`).join('\n')}`
    : '';

  const result = await generateStructuredOutput({
    prompt: `Extract all claims from this campaign:

AUDIENCE: ${state.campaignContext.audience || 'Not specified'}
GOAL: ${state.campaignContext.goal || 'Not specified'}
OFFER: ${state.campaignContext.offer || 'Not specified'}
${state.campaignContext.brief ? `BRIEF: ${state.campaignContext.brief}` : ''}
${evidenceContext}

Identify every claim made or implied. For each claim, determine:
1. The exact claim text
2. Whether it's a hard, soft, or unverified claim
3. Which category it belongs to
4. Your confidence that this claim is accurate and supportable
5. Which evidence item (if any) supports this claim`,
    schema: ClaimsExtractionSchema,
    system: `You are a claims extraction expert for marketing compliance. Your job is to identify every claim made or implied in marketing content.

CLAIM TYPES:
- hard: Factual, measurable, comparative, or quantified claims that require proof (e.g., "50% faster", "#1 rated", "SOC2 compliant")
- soft: Benefit statements and positioning that don't make absolute assertions (e.g., "helps teams collaborate", "designed for enterprise")
- unverified: Claims that sound good but have no supporting evidence (e.g., "industry-leading", "best-in-class")

CATEGORIES:
- performance: Speed, efficiency, productivity claims
- security: Data protection, compliance, certifications
- pricing: Cost, savings, ROI claims
- compliance: Regulatory, legal, certification claims
- generic: General benefits, positioning

Be thorough. Extract every claim, even implied ones.`,
    temperature: 0.5,
  });

  const candidates: ClaimCandidate[] = result.claims.map(claim => ({
    text: claim.text,
    claimType: claim.claimType,
    category: claim.category,
    confidence: claim.confidence,
    sourceContext: claim.sourceEvidence,
  }));

  const auditEvent: AuditEvent = {
    entityType: 'claim',
    entityId: 'pipeline',
    action: 'create',
    after: {
      step: 'propose_claims',
      candidateCount: candidates.length,
      candidates: candidates.map(c => ({ text: c.text, type: c.claimType })),
    },
    timestamp: new Date(),
  };

  return {
    claimCandidates: candidates,
    auditEvents: [auditEvent],
  };
}

/**
 * Node 3: Rule Validate Claims
 * Run deterministic policy engine validation (no AI - rules have final say)
 */
async function ruleValidateClaims(state: GraphStateType): Promise<Partial<GraphStateType>> {
  const results: Array<ClaimValidationResult & { claimIndex: number }> = [];

  for (let i = 0; i < state.claimCandidates.length; i++) {
    const candidate = state.claimCandidates[i];
    
    const context = {
      policy: state.policy,
      hasEvidence: !!candidate.sourceContext,
      linkedEvidenceCount: candidate.sourceContext ? 1 : 0,
    };

    const result = validateClaim(candidate.text, context);
    results.push({ ...result, claimIndex: i });
  }

  const blockedCount = results.filter(r => r.status === 'blocked').length;
  const needsProofCount = results.filter(r => r.status === 'needs_proof').length;
  const allowedCount = results.filter(r => r.status === 'allowed').length;

  const auditEvent: AuditEvent = {
    entityType: 'claim',
    entityId: 'pipeline',
    action: 'update',
    after: {
      step: 'rule_validate_claims',
      allowed: allowedCount,
      needsProof: needsProofCount,
      blocked: blockedCount,
      retryCount: state.retryCount,
    },
    timestamp: new Date(),
  };

  return {
    validationResults: results,
    auditEvents: [auditEvent],
  };
}

/**
 * Node 4: Propose Rewrites
 * Use AI SDK Gateway to suggest compliant rewrites for blocked/needs-proof claims
 */
async function proposeRewrites(state: GraphStateType): Promise<Partial<GraphStateType>> {
  // Get claims that need rewrites
  const claimsNeedingRewrites = state.validationResults
    .filter(r => r.status === 'blocked' || r.status === 'needs_proof')
    .map(r => ({
      text: state.claimCandidates[r.claimIndex].text,
      reasonCode: r.reasonCodes.join(', '),
      category: state.claimCandidates[r.claimIndex].category,
    }));

  if (claimsNeedingRewrites.length === 0) {
    return { retryCount: state.retryCount };
  }

  const forbiddenTerms = state.policy.forbiddenTerms.map(t => t.term);

  const rewrites = await generateCompliantRewrites(claimsNeedingRewrites, {
    mode: state.policy.mode,
    forbiddenTerms,
  });

  // Update claim candidates with rewrites
  const updatedCandidates = [...state.claimCandidates];
  
  for (const rewrite of rewrites.rewrites) {
    const originalIndex = state.claimCandidates.findIndex(
      c => c.text === rewrite.original
    );
    if (originalIndex !== -1) {
      updatedCandidates[originalIndex] = {
        ...updatedCandidates[originalIndex],
        text: rewrite.rewritten,
      };
    }
  }

  const auditEvent: AuditEvent = {
    entityType: 'claim',
    entityId: 'pipeline',
    action: 'update',
    after: {
      step: 'propose_rewrites',
      rewriteCount: rewrites.rewrites.length,
      rewrites: rewrites.rewrites.map(r => ({
        original: r.original,
        rewritten: r.rewritten,
      })),
    },
    timestamp: new Date(),
  };

  return {
    claimCandidates: updatedCandidates,
    retryCount: state.retryCount + 1,
    auditEvents: [auditEvent],
  };
}

/**
 * Node 5: Finalize Claims
 * Prepare final output with blocked items flagged for human review
 */
async function finalizeClaims(state: GraphStateType): Promise<Partial<GraphStateType>> {
  const finalClaims = state.claimCandidates.map((candidate, i) => {
    const validation = state.validationResults.find(r => r.claimIndex === i);
    
    let status: ClaimStatus;
    if (!validation) {
      status = 'draft';
    } else if (validation.status === 'allowed') {
      status = candidate.claimType === 'hard' ? 'ready_review' : 'approved';
    } else if (validation.status === 'needs_proof') {
      status = 'needs_proof';
    } else {
      status = 'blocked';
    }

    return {
      text: candidate.text,
      type: candidate.claimType,
      category: candidate.category,
      status,
      reasonCodes: validation?.reasonCodes || [],
      riskScore: validation?.riskScore || 0,
      requiredEvidenceTier: validation?.requiredEvidenceTier || null,
      suggestedRewrites: validation?.suggestedRewrites || [],
    };
  });

  const auditEvent: AuditEvent = {
    entityType: 'claim',
    entityId: 'pipeline',
    action: 'update',
    after: {
      step: 'finalize_claims',
      finalClaimCount: finalClaims.length,
      statusBreakdown: {
        approved: finalClaims.filter(c => c.status === 'approved').length,
        readyReview: finalClaims.filter(c => c.status === 'ready_review').length,
        needsProof: finalClaims.filter(c => c.status === 'needs_proof').length,
        blocked: finalClaims.filter(c => c.status === 'blocked').length,
      },
    },
    timestamp: new Date(),
  };

  return {
    finalClaims,
    auditEvents: [auditEvent],
  };
}

// ============================================================================
// Conditional Edge: Should Retry?
// ============================================================================

function shouldRetry(state: GraphStateType): string {
  const hasBlockedClaims = state.validationResults.some(
    r => r.status === 'blocked' || r.status === 'needs_proof'
  );
  
  // Max 2 retry attempts
  if (hasBlockedClaims && state.retryCount < 2) {
    return 'propose_rewrites';
  }
  
  return 'finalize_claims';
}

// ============================================================================
// Build the Graph
// ============================================================================

export function createClaimValidationGraph() {
  const workflow = new StateGraph(GraphState)
    // Add nodes
    .addNode('normalize_inputs', normalizeInputs)
    .addNode('propose_claims', proposeClaims)
    .addNode('rule_validate_claims', ruleValidateClaims)
    .addNode('propose_rewrites', proposeRewrites)
    .addNode('finalize_claims', finalizeClaims)
    
    // Add edges
    .addEdge(START, 'normalize_inputs')
    .addEdge('normalize_inputs', 'propose_claims')
    .addEdge('propose_claims', 'rule_validate_claims')
    .addConditionalEdges('rule_validate_claims', shouldRetry, {
      propose_rewrites: 'propose_rewrites',
      finalize_claims: 'finalize_claims',
    })
    .addEdge('propose_rewrites', 'rule_validate_claims')
    .addEdge('finalize_claims', END);

  return workflow.compile();
}

// ============================================================================
// Convenience Function: Run Validation Pipeline
// ============================================================================

export interface ValidationPipelineInput {
  policy: PolicyConfig;
  campaignContext: {
    audience?: string;
    goal?: string;
    offer?: string;
    industry?: string;
    brief?: string;
  };
  evidenceSummaries?: string[];
}

export interface ValidationPipelineOutput {
  claims: Array<{
    text: string;
    type: ClaimType;
    category: ClaimCategory;
    status: ClaimStatus;
    reasonCodes: ReasonCode[];
    riskScore: number;
    requiredEvidenceTier: EvidenceTier | null;
    suggestedRewrites: string[];
  }>;
  auditTrail: AuditEvent[];
  summary: {
    total: number;
    approved: number;
    needsReview: number;
    needsProof: number;
    blocked: number;
  };
}

export async function runClaimValidationPipeline(
  input: ValidationPipelineInput
): Promise<ValidationPipelineOutput> {
  const graph = createClaimValidationGraph();
  
  const result = await graph.invoke({
    policy: input.policy,
    campaignContext: input.campaignContext,
    evidenceSummaries: input.evidenceSummaries || [],
  });

  const claims = result.finalClaims;
  
  return {
    claims,
    auditTrail: result.auditEvents,
    summary: {
      total: claims.length,
      approved: claims.filter(c => c.status === 'approved').length,
      needsReview: claims.filter(c => c.status === 'ready_review').length,
      needsProof: claims.filter(c => c.status === 'needs_proof').length,
      blocked: claims.filter(c => c.status === 'blocked').length,
    },
  };
}

// ============================================================================
// Single Claim Validation (for real-time validation)
// ============================================================================

export async function validateSingleClaim(
  claimText: string,
  policy: PolicyConfig,
  options?: {
    hasEvidence?: boolean;
    evidenceTier?: EvidenceTier;
  }
): Promise<ClaimValidationResult> {
  const context = {
    policy,
    hasEvidence: options?.hasEvidence ?? false,
    evidenceTier: options?.evidenceTier,
    linkedEvidenceCount: options?.hasEvidence ? 1 : 0,
  };

  return validateClaim(claimText, context);
}
